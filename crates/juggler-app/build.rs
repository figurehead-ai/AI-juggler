//! Build script: generates Tauri context artifacts (window/capability
//! schemas) for the application crate.

// A build script stops the build with a message: there is no caller to
// hand an error to.
#![allow(clippy::expect_used)]

fn main() {
    // AJ-E2003: the app's own commands get permissions, so a window may
    // call only what its capability file grants (`capabilities/`).
    let commands: &'static [&'static str] = Box::leak(registered_commands().into_boxed_slice());
    main_window_set(commands);
    let manifest = tauri_build::AppManifest::new()
        .commands(commands)
        .permissions_path_pattern("permissions/*.toml");
    tauri_build::try_build(tauri_build::Attributes::new().app_manifest(manifest))
        .expect("tauri-build");
    crash_sender();
}

/// `permissions/generated-main-window.toml`: the main window's set, every
/// registered command (generated, so a new command needs no second list;
/// the terminal window's set, `permissions/terminal-window.toml`, is
/// written by hand and names only what that window calls).
fn main_window_set(commands: &[&str]) {
    let allowed: Vec<String> = commands
        .iter()
        .map(|name| format!("  \"allow-{}\",", name.replace('_', "-")))
        .collect();
    let toml = format!(
        "# Generated by build.rs from the app_commands! registry - DO NOT EDIT.\n\
         [[set]]\n\
         identifier = \"main-window\"\n\
         description = \"Every registered command: the main window's.\"\n\
         permissions = [\n{}\n]\n",
        allowed.join("\n")
    );
    let path = std::path::Path::new("permissions/generated-main-window.toml");
    if std::fs::read_to_string(path).ok().as_deref() != Some(toml.as_str()) {
        std::fs::create_dir_all("permissions").expect("permissions/");
        std::fs::write(path, toml).expect("write the main window's set");
    }
}

/// Every command in `src/lib.rs`'s `app_commands!` registry, by its
/// function name: the one list the invoke handler is also built from.
fn registered_commands() -> Vec<&'static str> {
    println!("cargo::rerun-if-changed=src/lib.rs");
    let source = std::fs::read_to_string("src/lib.rs").expect("src/lib.rs");
    let start = source
        .find("macro_rules! app_commands")
        .expect("the app_commands! registry");
    let body = &source[start..];
    let body = &body[..body.find("\n}\n").expect("the registry's end")];
    let mut names: Vec<&'static str> = body
        .lines()
        .filter_map(|line| {
            let mut words = line.split_whitespace();
            let access = words.next()?;
            let path = words.next()?.strip_suffix(',')?;
            (matches!(access, "Read" | "Write") && words.next().is_none())
                .then(|| path.rsplit("::").next())
                .flatten()
                .map(|name| &*Box::leak(name.to_owned().into_boxed_str()))
        })
        .collect();
    assert!(names.len() > 400, "the registry parse found only {} commands", names.len());
    // A command declared `#[tauri::command(rename = "x")]` is invoked as x.
    let renames = renamed_commands();
    for name in &mut names {
        if let Some(invoked) = renames.get(*name) {
            *name = invoked;
        }
    }
    names.sort_unstable();
    let count = names.len();
    names.dedup();
    assert_eq!(count, names.len(), "two registered commands share a name");
    names
}

/// AJ-E1516: the crash report sender (`src/crash_send.rs`) is built only
/// into a release build given the reporting service's address. No
/// workflow sets it, so no build has a sender until the service exists.
fn crash_sender() {
    println!("cargo::rustc-check-cfg=cfg(crash_sender)");
    println!("cargo::rerun-if-env-changed=AI_JUGGLER_CRASH_ENDPOINT");
    let address = std::env::var("AI_JUGGLER_CRASH_ENDPOINT").unwrap_or_default();
    let release = std::env::var("PROFILE").is_ok_and(|profile| profile == "release");
    if release && address.starts_with("https://") {
        println!("cargo::rustc-cfg=crash_sender");
    }
}

/// `function name → invoked name` for every `#[tauri::command(rename = …)]`
/// under `src/`.
fn renamed_commands() -> std::collections::HashMap<String, &'static str> {
    let mut found = std::collections::HashMap::new();
    let mut stack = vec![std::path::PathBuf::from("src")];
    while let Some(dir) = stack.pop() {
        for entry in std::fs::read_dir(&dir).expect("src/").flatten() {
            let path = entry.path();
            if path.is_dir() {
                stack.push(path);
                continue;
            }
            if path.extension().is_none_or(|e| e != "rs") {
                continue;
            }
            println!("cargo::rerun-if-changed={}", path.display());
            let text = std::fs::read_to_string(&path).expect("a source file");
            let mut pending: Option<String> = None;
            for line in text.lines().map(str::trim) {
                if let Some(rest) = line.strip_prefix("#[tauri::command(") {
                    pending = rest
                        .split("rename")
                        .nth(1)
                        .and_then(|r| r.split('"').nth(1))
                        .map(str::to_owned);
                } else if let Some(name) = pending.as_ref().and(
                    ["pub async fn ", "pub fn ", "async fn ", "fn "]
                        .iter()
                        .find_map(|start| line.strip_prefix(start)),
                ) {
                    let function = name.split(['(', '<']).next().unwrap_or_default().trim().to_owned();
                    let invoked = pending.take().unwrap_or_default();
                    found.insert(function, &*Box::leak(invoked.into_boxed_str()));
                }
            }
        }
    }
    found
}
