#!/usr/bin/env python3
"""AJ-E1102: generates crates/juggler-stats/src/generated.rs from
stats/schema.v1.json — the closed, typed events and gauges.

Every dimension becomes a Rust enum; there is no String anywhere, so no
free text, path or label can be recorded. The crate's parity test
re-reads the schema and checks the generated tables match it exactly;
`--check` fails when the committed file is stale (run by `just verify`).

Usage: scripts/gen_stats_events.py [--check]
"""
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "stats" / "schema.v1.json"
OUT = ROOT / "crates" / "juggler-stats" / "src" / "generated.rs"


def pascal(text: str) -> str:
    parts = re.split(r"[^0-9A-Za-z]+", text)
    return "".join(p[:1].upper() + p[1:] for p in parts if p)


def variant(value: str) -> str:
    """A Rust variant name for an enum wire value."""
    special = {"<1w": "LessThanOneWeek", "10+": "TenOrMore", "4-5": "FourToFive", "6-9": "SixToNine",
               "0": "Zero", "1": "One", "2": "Two", "3": "Three"}
    if value in special:
        return special[value]
    name = pascal(value.replace(".", " dot ").replace("-", " "))
    if name[:1].isdigit():
        name = "V" + name
    return name


def main() -> int:
    schema = json.loads(SCHEMA.read_text())
    enums = schema["enums"]
    out: list[str] = []
    w = out.append
    w("// @generated by scripts/gen_stats_events.py from stats/schema.v1.json — do not edit.")
    w("// AJ-E1102: the closed, typed usage-statistics vocabulary. No String anywhere.")
    w("")
    w("#![allow(missing_docs, clippy::too_many_lines, clippy::match_same_arms, clippy::unreadable_literal)]")
    w("")
    w("/// The schema version these types were generated from.")
    w(f"pub const SCHEMA_VERSION: u32 = {schema['schema']};")
    w(f"/// Default per-report cap for a counter.")
    w(f"pub const COUNTER_MAX: u64 = {schema['limits']['counter_max']};")
    w(f"/// Default per-report cap for a histogram's total.")
    w(f"pub const HISTOGRAM_TOTAL_MAX: u64 = {schema['limits']['histogram_total_max']};")
    w("")

    defined: dict[str, list[str]] = {}

    def enum(name: str, values: list[str], doc: str) -> None:
        if name in defined:
            return
        defined[name] = values
        w(f"/// {doc}")
        w("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]")
        w(f"pub enum {name} {{")
        for value in values:
            w(f"    /// `{value}`")
            w(f"    {variant(value)},")
        w("}")
        w("")
        w(f"impl {name} {{")
        w("    /// Every value, in schema order.")
        w(f"    pub const ALL: [Self; {len(values)}] = [{', '.join('Self::' + variant(v) for v in values)}];")
        w("    /// The value as the report writes it.")
        w("    #[must_use]")
        w("    pub const fn wire(self) -> &'static str {")
        w("        match self {")
        for value in values:
            w(f"            Self::{variant(value)} => {json.dumps(value)},")
        w("        }")
        w("    }")
        w("}")
        w("")

    for key, values in enums.items():
        enum(pascal(key), values, f"Schema enum `{key}`.")

    def dim_type(metric: str, dim: str, spec) -> str:
        if isinstance(spec, str):
            return pascal(spec)
        name = pascal(metric) + pascal(dim)
        enum(name, spec, f"`{dim}` of `{metric}`.")
        return name

    def gauge_type(metric: str, spec) -> str:
        if isinstance(spec, str):
            return pascal(spec)
        name = pascal(metric) + "Value"
        enum(name, spec, f"The value of `{metric}`.")
        return name

    events, gauges = [], []
    for name, metric in schema["metrics"].items():
        dims = [(d, dim_type(name, d, spec)) for d, spec in metric.get("dims", {}).items()]
        if metric["type"] == "gauge":
            if "values" in metric:
                value_kind = "count" if metric["values"] == "count_bucket" else gauge_type(name, metric["values"])
            else:
                value_kind = "version"
            gauges.append((name, metric, dims, value_kind))
        else:
            events.append((name, metric, dims))

    def field(d: str) -> str:
        return {"type": "kind"}.get(d, d)

    # --- StatEvent ---------------------------------------------------------
    w("/// One countable thing that happened (a counter or histogram metric).")
    w("#[derive(Clone, Copy, Debug, PartialEq)]")
    w("pub enum StatEvent {")
    for name, metric, dims in events:
        fields = [f"{field(d)}: {t}" for d, t in dims]
        if metric["type"] == "histogram":
            fields.append("value: f64")
        w(f"    /// `{name}` ({metric['type']})")
        w(f"    {pascal(name)}" + (" { " + ", ".join(fields) + " }," if fields else ","))
    w("}")
    w("")
    w("impl StatEvent {")
    w("    /// The metric name.")
    w("    #[must_use]")
    w("    pub const fn metric(&self) -> &'static str {")
    w("        match self {")
    for name, metric, dims in events:
        pattern = " { .. }" if dims or metric["type"] == "histogram" else ""
        w(f"            Self::{pascal(name)}{pattern} => {json.dumps(name)},")
    w("        }")
    w("    }")
    w("")
    w("    /// The dimensions, in schema order, as wire values.")
    w("    #[must_use]")
    w("    pub fn dims(&self) -> Vec<(&'static str, &'static str)> {")
    w("        match self {")
    for name, metric, dims in events:
        if not dims:
            pattern = " { .. }" if metric["type"] == "histogram" else ""
            w(f"            Self::{pascal(name)}{pattern} => Vec::new(),")
            continue
        binds = ", ".join(field(d) for d, _ in dims) + (", .." if metric["type"] == "histogram" else "")
        pairs = ", ".join(f"({json.dumps(d)}, {field(d)}.wire())" for d, _ in dims)
        w(f"            Self::{pascal(name)} {{ {binds} }} => vec![{pairs}],")
    w("        }")
    w("    }")
    w("")
    w("    /// One value of every variant (each dimension at its first value),")
    w("    /// for the parity test.")
    w("    #[doc(hidden)]")
    w("    #[must_use]")
    w("    pub fn examples() -> Vec<Self> {")
    w("        vec![")
    for name, metric, dims in events:
        fields = [f"{field(d)}: {t}::ALL[0]" for d, t in dims]
        if metric["type"] == "histogram":
            fields.append("value: 0.0")
        w(f"            Self::{pascal(name)}" + (" { " + ", ".join(fields) + " }," if fields else ","))
    w("        ]")
    w("    }")
    w("")
    w("    /// The observed value, for a histogram metric.")
    w("    #[must_use]")
    w("    pub const fn observation(&self) -> Option<f64> {")
    w("        match self {")
    for name, metric, dims in events:
        if metric["type"] == "histogram":
            w(f"            Self::{pascal(name)} {{ value, .. }} => Some(*value),")
    w("            _ => None,")
    w("        }")
    w("    }")
    w("}")
    w("")

    # --- StatGauge ---------------------------------------------------------
    w("/// An end-of-week snapshot value (a gauge metric).")
    w("#[derive(Clone, Copy, Debug, PartialEq, Eq)]")
    w("pub enum StatGauge {")
    for name, metric, dims, value_kind in gauges:
        fields = [f"{field(d)}: {t}" for d, t in dims]
        if value_kind == "count":
            fields.append("count: u64")
        elif value_kind == "version":
            fields.append("version: crate::CliVersion")
        else:
            fields.append(f"value: {value_kind}")
        w(f"    /// `{name}`")
        w(f"    {pascal(name)} {{ {', '.join(fields)} }},")
    w("}")
    w("")
    w("impl StatGauge {")
    w("    /// The metric name.")
    w("    #[must_use]")
    w("    pub const fn metric(&self) -> &'static str {")
    w("        match self {")
    for name, *_ in gauges:
        w(f"            Self::{pascal(name)} {{ .. }} => {json.dumps(name)},")
    w("        }")
    w("    }")
    w("")
    w("    /// The dimensions, in schema order, as wire values.")
    w("    #[must_use]")
    w("    pub fn dims(&self) -> Vec<(&'static str, &'static str)> {")
    w("        match self {")
    for name, metric, dims, _ in gauges:
        if not dims:
            w(f"            Self::{pascal(name)} {{ .. }} => Vec::new(),")
            continue
        binds = ", ".join(field(d) for d, _ in dims) + ", .."
        pairs = ", ".join(f"({json.dumps(d)}, {field(d)}.wire())" for d, _ in dims)
        w(f"            Self::{pascal(name)} {{ {binds} }} => vec![{pairs}],")
    w("        }")
    w("    }")
    w("")
    w("    /// One value of every variant, for the parity test.")
    w("    #[doc(hidden)]")
    w("    #[must_use]")
    w("    pub fn examples() -> Vec<Self> {")
    w("        vec![")
    for name, metric, dims, value_kind in gauges:
        fields = [f"{field(d)}: {t}::ALL[0]" for d, t in dims]
        if value_kind == "count":
            fields.append("count: 0")
        elif value_kind == "version":
            fields.append("version: crate::CliVersion::Other")
        else:
            fields.append(f"value: {value_kind}::ALL[0]")
        w(f"            Self::{pascal(name)} {{ {', '.join(fields)} }},")
    w("        ]")
    w("    }")
    w("")
    w("    /// The bucket label the report carries.")
    w("    #[must_use]")
    w("    pub fn value(&self) -> String {")
    w("        match self {")
    for name, metric, dims, value_kind in gauges:
        if value_kind == "count":
            w(f"            Self::{pascal(name)} {{ count, .. }} => CountBucket::of(*count).wire().to_owned(),")
        elif value_kind == "version":
            w(f"            Self::{pascal(name)} {{ version, .. }} => version.wire(),")
        else:
            w(f"            Self::{pascal(name)} {{ value, .. }} => value.wire().to_owned(),")
    w("        }")
    w("    }")
    w("}")
    w("")

    # --- the metadata table (the parity test compares it to the schema) ------
    w("/// One metric as the schema declares it.")
    w("#[derive(Clone, Copy, Debug)]")
    w("pub struct MetricMeta {")
    w("    /// Its name.")
    w("    pub name: &'static str,")
    w("    /// `counter` | `gauge` | `histogram`.")
    w("    pub kind: &'static str,")
    w("    /// Each dimension and its allowed values.")
    w("    pub dims: &'static [(&'static str, &'static [&'static str])],")
    w("    /// Histogram bucket labels.")
    w("    pub buckets: &'static [&'static str],")
    w("    /// Allowed gauge values (empty for the version pattern).")
    w("    pub values: &'static [&'static str],")
    w("    /// The per-report cap.")
    w("    pub max: u64,")
    w("}")
    w("")
    w("/// Every metric, in schema order.")
    w("pub const METRICS: &[MetricMeta] = &[")

    def values_of(spec) -> list[str]:
        return enums[spec] if isinstance(spec, str) else spec

    for name, metric in schema["metrics"].items():
        dims = ", ".join(
            f"({json.dumps(d)}, &[{', '.join(json.dumps(v) for v in values_of(spec))}])"
            for d, spec in metric.get("dims", {}).items()
        )
        buckets = ", ".join(json.dumps(b) for b in metric.get("buckets", []))
        gvalues = ", ".join(json.dumps(v) for v in values_of(metric["values"])) if "values" in metric else ""
        default_max = schema["limits"]["histogram_total_max"] if metric["type"] == "histogram" else schema["limits"]["counter_max"]
        w(f"    MetricMeta {{ name: {json.dumps(name)}, kind: {json.dumps(metric['type'])}, dims: &[{dims}], buckets: &[{buckets}], values: &[{gvalues}], max: {metric.get('max', default_max)} }},")
    w("];")
    w("")
    text = "\n".join(out) + "\n"
    # Formatted as `cargo fmt` would, so the check survives a workspace fmt.
    text = subprocess.run(
        ["rustfmt", "--edition", "2024", "--config-path", str(ROOT), "--emit", "stdout"],
        input=text, capture_output=True, text=True, check=True, cwd=ROOT,
    ).stdout
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("stats-events: crates/juggler-stats/src/generated.rs is out of date — run scripts/gen_stats_events.py", file=sys.stderr)
            return 1
        print("stats-events: up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"stats-events: wrote {OUT.relative_to(ROOT)} ({len(events)} events, {len(gauges)} gauges)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
