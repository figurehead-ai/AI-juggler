#!/usr/bin/env python3
"""AJ-E3301: deterministic all-pairs covering arrays for 0.4's screens.

Every pair of values of any two options appears together in at least one
row, so L3's journeys (one test per row) cover every pairwise interaction
in about 50 rows instead of millions. The arrays are generated by a fixed
greedy (IPOG: grow by option, then fill the pairs left), with no
randomness, so the same definition always gives the same rows; they are
checked in under docs/qa/pairwise/ with a coverage report naming the row
that covers each pair. Named risky triples are written by hand on top
(the validation plan, §3).

Usage:
  pairwise.py write     regenerate docs/qa/pairwise/*.csv and *-coverage.md
  pairwise.py check     the checked-in arrays are current and cover every pair
  pairwise.py --selftest
"""
