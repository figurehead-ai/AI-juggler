def pairs_of(names: list[str], values: dict[str, list[str]]) -> set[tuple[int, str, int, str]]:
    return {(i, a, j, b) for i, j in itertools.combinations(range(len(names)), 2) for a in values[names[i]] for b in values[names[j]]}


def covered(row: list[str | None], i: int, j: int) -> tuple[int, str, int, str] | None:
    a, b = row[i], row[j]
    return None if a is None or b is None else (i, a, j, b)


def generate(options: dict[str, list[str]]) -> list[list[str]]:
    """IPOG: rows for the first two options in full, then each next option
    added to every row (the value covering most new pairs, the first on a
    tie), then rows added for the pairs still uncovered."""
    names = list(options)
    rows: list[list[str | None]] = [[a, b] for a in options[names[0]] for b in options[names[1]]]
    for k in range(2, len(names)):
        missing = {(i, a, k, b) for i in range(k) for a in options[names[i]] for b in options[names[k]]}
        for row in rows:
            best, gain = options[names[k]][0], -1
            for value in options[names[k]]:
                g = sum((i, row[i], k, value) in missing for i in range(k) if row[i] is not None)
                if g > gain:
                    best, gain = value, g
            row.append(best)
            missing -= {(i, row[i], k, best) for i in range(k)}
        extra: list[list[str | None]] = []
        for (i, a, _, b) in sorted(missing, key=lambda p: (names[p[0]], options[names[p[0]]].index(p[1]), options[names[k]].index(p[3]))):
            for row in extra:
                if row[k] == b and row[i] in (None, a):
                    row[i] = a
                    break
            else:
                fresh: list[str | None] = [None] * (k + 1)
                fresh[i], fresh[k] = a, b
                extra.append(fresh)
        rows.extend(extra)
    # Fill the free cells with each option's first value (any value keeps the pairs).
    for row in rows:
        for at, cell in enumerate(row):
            if cell is None:
                row[at] = options[names[at]][0]
    return [list(map(str, row)) for row in rows]


def coverage(options: dict[str, list[str]], rows: list[list[str]]) -> tuple[list[str], int]:
    names = list(options)
    lines, uncovered = [], 0
    for i, j in itertools.combinations(range(len(names)), 2):
        for a in options[names[i]]:
            for b in options[names[j]]:
                where = next((n for n, row in enumerate(rows, 1) if row[i] == a and row[j] == b), None)
                if where is None:
                    uncovered += 1
                lines.append(f"| {names[i]}={a} | {names[j]}={b} | {where if where else 'UNCOVERED'} |")
    return lines, uncovered


def render(name: str, options: dict[str, list[str]]) -> tuple[str, str, int, int]:
    rows = generate(options)
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(["row", *options])
    for n, row in enumerate(rows, 1):
        writer.writerow([n, *row])
    lines, uncovered = coverage(options, rows)
    report = "\n".join([
        f"# {name}: pairwise coverage",
        "",
        f"Generated by `scripts/qa/pairwise.py write` — do not edit. {len(rows)} rows cover {len(lines)} pairs"
        + (f"; {uncovered} UNCOVERED." if uncovered else ", every one."),
        "",
        "| One option | The other | Row |",
        "|---|---|---|",
        *lines,
        "",
    ])
    return buffer.getvalue(), report, len(rows), uncovered


def selftest() -> None:
    small = {"a": ["0", "1"], "b": ["0", "1"], "c": ["0", "1"], "d": ["x", "y", "z"]}
    rows = generate(small)
    _, uncovered = coverage(small, rows)
    assert uncovered == 0 and len(rows) <= 9, rows
    assert generate(small) == rows, "not deterministic"
    for name, options in MATRICES.items():
        rows = generate(options)
        assert coverage(options, rows)[1] == 0, name
        full = 1
        for values in options.values():
            full *= len(values)
        assert len(rows) < full, name
    print("pairwise selftest: ok")


def main(argv: list[str]) -> int:
    if argv[:1] == ["--selftest"]:
        selftest()
        return 0
    if argv[:1] not in (["write"], ["check"]):
        print(__doc__)
        return 2
    stale = []
    for name, options in MATRICES.items():
        table, report, n, uncovered = render(name, options)
        if uncovered:
            print(f"pairwise: {name} leaves {uncovered} pairs uncovered", file=sys.stderr)
            return 1
        for path, text in ((OUT / f"{name}.csv", table), (OUT / f"{name}-coverage.md", report)):
            if argv[0] == "write":
                OUT.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
            elif not path.exists() or path.read_text() != text:
                stale.append(path.relative_to(ROOT))
        print(f"pairwise: {name}: {n} rows, every pair covered")
    if stale:
        print("pairwise: stale (run `scripts/qa/pairwise.py write`): " + ", ".join(map(str, stale)), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
