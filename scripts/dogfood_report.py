#!/usr/bin/env python3
"""AJ-E809 — the weekly dogfood report from the run sheets.

  dogfood_report.py                 write docs/qa/evidence/AJ-E809/report.md from runs.csv
  dogfood_report.py --selftest      check the arithmetic on built-in rows

Reads docs/qa/evidence/AJ-E809/runs.csv (one row per scripted task run;
see run-sheet.md) and reports the beta-exit thresholds (AJ-E809 Req.3):
unaided completion >= 80 %, A->B->A continuity >= 80 %, zero false
cleanup kills, median switch completion < 2 min. It also reports cohort
coverage (Req.1: >= 3 personas, >= 5 active users a week, 4 weeks) and
every friction note not yet filed as a task (Req.4). Exit 1 while any
threshold or the cohort requirement is unmet: the beta gate can't pass
on this programme until the report says MET.
"""
from __future__ import annotations

import csv
import io
import statistics
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIR = ROOT / "docs/qa/evidence/AJ-E809"
PERSONAS = {"maya", "devon", "priya"}
TASKS = {"quota-wall-switch", "switch-back", "zombie-cleanup", "cross-provider-switch", "fleet-join"}
SWITCH_TASKS = {"quota-wall-switch", "switch-back", "cross-provider-switch"}
COLUMNS = [
    "week", "date", "participant", "persona", "task", "completed", "unaided",
    "minutes", "errors", "continuity", "false_kill", "friction", "filed_task", "capture",
]


def yes(value: str) -> bool:
    return value.strip().lower() == "yes"


def pct(part: int, whole: int) -> str:
    return "—" if whole == 0 else f"{100 * part / whole:.0f} %"


def analyse(rows: list[dict[str, str]]) -> tuple[list[str], bool]:
    problems = []
    for i, row in enumerate(rows, start=2):
        if row["persona"] not in PERSONAS:
            problems.append(f"line {i}: persona {row['persona']!r} is not one of {sorted(PERSONAS)}")
        if row["task"] not in TASKS:
            problems.append(f"line {i}: task {row['task']!r} is not one of {sorted(TASKS)}")
    runs = len(rows)
    unaided = sum(1 for r in rows if yes(r["completed"]) and yes(r["unaided"]))
    judged = [r for r in rows if r["continuity"].strip().lower() in {"yes", "no"}]
    continuous = sum(1 for r in judged if yes(r["continuity"]))
    false_kills = sum(1 for r in rows if yes(r["false_kill"]))
    switch_minutes = [
        float(r["minutes"]) for r in rows if r["task"] in SWITCH_TASKS and yes(r["completed"]) and r["minutes"].strip()
    ]
    median_switch = statistics.median(switch_minutes) if switch_minutes else None
    weeks: dict[str, set[str]] = defaultdict(set)
    personas: set[str] = set()
    for r in rows:
        weeks[r["week"]].add(r["participant"])
        personas.add(r["persona"])
    full_weeks = sorted(w for w, people in weeks.items() if len(people) >= 5)
    unfiled = [r for r in rows if r["friction"].strip() and not r["filed_task"].strip()]

    checks = [
        ("Unaided task completion", ">= 80 %", pct(unaided, runs), runs > 0 and unaided / runs >= 0.8),
        ("A→B→A continuity (judged by the user)", ">= 80 %", pct(continuous, len(judged)), bool(judged) and continuous / len(judged) >= 0.8),
        ("False cleanup kills", "0", str(false_kills), runs > 0 and false_kills == 0),
        ("Median switch completion", "< 2 min", "—" if median_switch is None else f"{median_switch:.1f} min", median_switch is not None and median_switch < 2.0),
        ("Cohort: personas covered", ">= 3", f"{len(personas & PERSONAS)} ({', '.join(sorted(personas & PERSONAS)) or 'none'})", len(personas & PERSONAS) >= 3),
        ("Cohort: weeks with >= 5 active users", ">= 4", f"{len(full_weeks)} ({', '.join(full_weeks) or 'none'})", len(full_weeks) >= 4),
        ("Friction notes filed as tasks", "all, within 48 h", f"{len(unfiled)} unfiled", not unfiled),
    ]
    met = all(ok for *_, ok in checks) and not problems
    lines = [
        "# AJ-E809 — dogfood programme report",
        "",
        "Generated by `scripts/dogfood_report.py` from [`runs.csv`](runs.csv). Do not edit by hand.",
        "",
        f"Runs: **{runs}** · participants: **{len({r['participant'] for r in rows})}** · weeks: **{len(weeks)}**",
        "",
        "| Threshold | Target | Measured | Verdict |",
        "|---|---|---|---|",
        *[f"| {name} | {target} | {value} | {'MET' if ok else 'NOT MET'} |" for name, target, value, ok in checks],
        "",
        f"**Beta-exit (B2/B3): {'MET' if met else 'NOT MET'}.**",
        "",
    ]
    by_task: dict[str, list[dict[str, str]]] = defaultdict(list)
    for r in rows:
        by_task[r["task"]].append(r)
    if rows:
        lines += ["## By task", "", "| Task | Runs | Unaided | Median minutes | Errors |", "|---|---|---|---|---|"]
        for task in sorted(by_task):
            group = by_task[task]
            minutes = [float(r["minutes"]) for r in group if r["minutes"].strip()]
            lines.append(
                f"| {task} | {len(group)} | {pct(sum(1 for r in group if yes(r['completed']) and yes(r['unaided'])), len(group))} | "
                f"{statistics.median(minutes):.1f} | {sum(int(r['errors'] or 0) for r in group)} |"
                if minutes else
                f"| {task} | {len(group)} | — | — | {sum(int(r['errors'] or 0) for r in group)} |"
            )
        lines.append("")
    if unfiled:
        lines += ["## Friction not yet filed (file within 48 h)", ""]
        lines += [f"- {r['date']} · {r['persona']} · {r['task']}: “{r['friction'].strip()}”" for r in unfiled]
        lines.append("")
    if problems:
        lines += ["## Sheet problems", "", *[f"- {p}" for p in problems], ""]
    return lines, met


def read(text: str) -> list[dict[str, str]]:
    reader = csv.DictReader(io.StringIO(text))
    missing = [c for c in COLUMNS if c not in (reader.fieldnames or [])]
    if missing:
        raise SystemExit(f"runs.csv is missing columns: {', '.join(missing)}")
    return [{k: (v or "") for k, v in row.items()} for row in reader]


def selftest() -> int:
    header = ",".join(COLUMNS)
    rows = [header]
    people = [("P01", "maya"), ("P02", "devon"), ("P03", "priya"), ("P04", "maya"), ("P05", "devon")]
    for week in ("W1", "W2", "W3", "W4"):
        for pid, persona in people:
            rows.append(f"{week},2026-11-02,{pid},{persona},quota-wall-switch,yes,yes,1.5,0,na,no,,,")
            rows.append(f"{week},2026-11-02,{pid},{persona},switch-back,yes,yes,1.0,0,yes,no,,,")
    lines, met = analyse(read("\n".join(rows)))
    assert met, "\n".join(lines)
    # One false kill fails the gate on its own.
    rows.append("W4,2026-11-03,P01,maya,zombie-cleanup,yes,yes,3,0,na,yes,killed my dev server,AJ-E999,")
    lines, met = analyse(read("\n".join(rows)))
    assert not met and "| False cleanup kills | 0 | 1 | NOT MET |" in lines
    # An unfiled friction note fails it too.
    rows[-1] = "W4,2026-11-03,P01,maya,zombie-cleanup,yes,yes,3,0,na,no,the Undo was hard to find,,"
    lines, met = analyse(read("\n".join(rows)))
    assert not met and any("1 unfiled" in line for line in lines)
    # Three weeks are not four.
    lines, met = analyse(read("\n".join(r for r in rows if not r.startswith("W4"))))
    assert not met
    print("dogfood-report selftest: OK (met, false kill, unfiled friction, short cohort)")
    return 0


def main() -> int:
    if sys.argv[1:] == ["--selftest"]:
        return selftest()
    source = DIR / "runs.csv"
    lines, met = analyse(read(source.read_text()))
    (DIR / "report.md").write_text("\n".join(lines))
    print(f"{(DIR / 'report.md').relative_to(ROOT)}: beta-exit {'MET' if met else 'NOT MET'}")
    return 0 if met else 1


if __name__ == "__main__":
    sys.exit(main())
