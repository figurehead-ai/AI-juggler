#!/usr/bin/env python3
"""AJ-E804 Req.1: summarise the per-test axe scans of the gallery.

Reads docs/qa/evidence/AJ-E804/axe/*.json (written by
ui/tests/visual/axe-gallery.ts under AJ_AXE_GALLERY=1) and writes
docs/qa/evidence/AJ-E804/axe-summary.md (states scanned, violations by
impact, every moderate/minor rule with the task that owns it (from
docs/qa/evidence/AJ-E804/axe-owners.json). Exit 1 on any critical or
serious violation, or a moderate rule with no owning task.
"""
from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EVIDENCE = ROOT / "docs/qa/evidence/AJ-E804"


def main() -> int:
    files = sorted((EVIDENCE / "axe").glob("*.json"))
    if not files:
        print("no axe scans found — run `just a11y-gate`", file=sys.stderr)
        return 1
    owners_path = EVIDENCE / "axe-owners.json"
    owners: dict[str, str] = json.loads(owners_path.read_text()) if owners_path.exists() else {}
    combined: list[dict] = []
    states = 0
    totals: dict[str, int] = defaultdict(int)
    by_rule: dict[tuple[str, str], list[str]] = defaultdict(list)
    for path in files:
        record = json.loads(path.read_text())
        combined.append(record)
        for scan in record["scans"]:
            states += 1
            for finding in scan["findings"]:
                totals[finding["impact"]] += 1
                by_rule[(finding["impact"], finding["id"])].append(scan["state"])
    blocking = totals["critical"] + totals["serious"]
    unowned = [rule for (impact, rule) in by_rule if impact == "moderate" and rule not in owners]
    lines = [
        "# AJ-E804 — axe-core on every gallery state",
        "",
        "Generated by `scripts/axe_summary.py` from `axe/*.json`",
        "(`just a11y-gate`). Rules: WCAG 2.0, 2.1 and 2.2, levels A and AA.",
        "",
        f"- Gallery states scanned: **{states}** (in {len(files)} tests)",
        f"- Critical: **{totals['critical']}** · serious: **{totals['serious']}**"
        f" · moderate: **{totals['moderate']}** · minor: **{totals['minor']}**",
        f"- Verdict: **{'PASS' if blocking == 0 and not unowned else 'FAIL'}**"
        " (requires 0 critical, 0 serious, and every moderate rule owned by a task)",
        "",
    ]
    if by_rule:
        lines += ["| Impact | Rule | States | Owner | Example |", "|---|---|---|---|---|"]
        order = {"critical": 0, "serious": 1, "moderate": 2, "minor": 3}
        for (impact, rule), where in sorted(by_rule.items(), key=lambda kv: (order.get(kv[0][0], 9), kv[0][1])):
            owner = owners.get(rule, "—" if impact == "minor" else "UNOWNED")
            lines.append(f"| {impact} | `{rule}` | {len(where)} | {owner} | `{where[0]}` |")
        lines.append("")
    (EVIDENCE / "axe-summary.md").write_text("\n".join(lines))
    # One committed file; the per-test scans (axe/) are git-ignored.
    combined.sort(key=lambda r: r["test"])
    (EVIDENCE / "axe-gallery.json").write_text(json.dumps(combined, separators=(",", ":")) + "\n")
    print("\n".join(lines[5:8]))
    return 0 if blocking == 0 and not unowned else 1


if __name__ == "__main__":
    sys.exit(main())
